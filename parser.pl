% Настройка среды: двойные кавычки "..." всегда обрабатываем как списки кодов
:- set_prolog_flag(double_quotes, codes).

% 1. Синтаксический базис по Вирту (Вынос терминаторов)
is_terminator(44).  % Код 0', (запятая)
is_terminator(10).  % Код 0'\n (перенос строки)

% 2. Уровень Файла (csv_file//1) — Марковский приоритет правил (от частного к общему)
csv_file([Line|Rest]) -->
    csv_line(Line),
    !,
    (   "\n"
    ->  csv_file(Rest)
    ;   { Rest = [] }
    ).

csv_file([]) -->
    [],
    !.

% 3. Уровень Строки (csv_line//1) — Сборка ячеек и поглощение запятых
csv_line([Cell|Rest]) -->
    cell(Cell),
    (   ","                 
    ->  csv_line(Rest)      
    ;   { Rest = [] }       
    ).

% 4. Уровень Ячейки (cell//1) — Рождение атома в Универсуме Эрбрана
cell(Atom) --> 
    parseCSV(Codes), 
    { atom_codes(Atom, Codes) }.

% 5. Сборщик кодов (parseCSV//1) — Рекурсивный коиндуктивный деструктор
parseCSV([Char|Codes]) --> 
    [Char], 
    { \+ is_terminator(Char) }, 
    !, 
    parseCSV(Codes).

parseCSV([]) --> 
    [].




